import { prisma } from "@/lib/prisma";
import { agentFromBearer } from "@/lib/agents";
import { displayNames } from "@/lib/chat";
import { broadcastWorkspaceEvent } from "@/lib/realtime/broadcast";
import {
  TOUCH_WINDOW_MS,
  WARN_WINDOW_MS,
  readJson,
  relPath,
  touchFiles,
  unauthorized,
} from "@/lib/hooks";

export const dynamic = "force-dynamic";

export async function POST(req: Request) {
  const agent = await agentFromBearer(req);
  if (!agent) return unauthorized();
  const body = await readJson(req);
  const input = (body.tool_input ?? {}) as { file_path?: unknown };
  const rel = relPath(input.file_path, body.cwd);
  if (!rel) return new Response("", { status: 200 });

  const now = Date.now();
  const other = await prisma.fileActivity.findFirst({
    where: {
      workspaceId: agent.workspaceId,
      path: rel,
      updatedAt: { gt: new Date(now - TOUCH_WINDOW_MS) },
      agent: { ownerUserId: { not: agent.ownerUserId } },
    },
    orderBy: { updatedAt: "desc" },
    include: { agent: true },
  });

  if (other) {
    const mine = await prisma.fileActivity.findUnique({
      where: { agentId_path: { agentId: agent.id, path: rel } },
    });
    const warned = mine?.warnedAt && now - mine.warnedAt.getTime() < WARN_WINDOW_MS;
    if (!warned) {
      // Remember the warning without counting as "in the file": updatedAt stays old.
      await prisma.fileActivity.upsert({
        where: { agentId_path: { agentId: agent.id, path: rel } },
        update: { warnedAt: new Date(now) },
        create: {
          workspaceId: agent.workspaceId,
          agentId: agent.id,
          path: rel,
          updatedAt: new Date(0),
          warnedAt: new Date(now),
        },
      });
      const names = await displayNames(agent.workspaceId);
      const who = names.get(other.agent.ownerUserId) ?? other.agent.ownerUserId;
      const mins = Math.max(1, Math.floor((now - other.updatedAt.getTime()) / 60_000));
      const intent = other.agent.intent?.trim() || "unknown";
      const reason =
        `STOPPED BY THE ROOM. ${who} is working in ${rel} right now (started ${mins} min ago). ` +
        `${who}'s task: "${intent}". ` +
        `Do not edit this file and do not try another way around. Tell the user this in one short sentence, ` +
        `then offer exactly these three choices and wait for their answer: ` +
        `1) Continue with the same edit anyway. ` +
        `2) A changed plan that fits with what ${who} is doing (write the concrete plan yourself). ` +
        `3) Message ${who} and wait (you would send it with the message_person tool).`;
      await broadcastWorkspaceEvent(agent.workspaceId, { type: "agents_changed" });
      return Response.json({
        hookSpecificOutput: {
          hookEventName: "PreToolUse",
          permissionDecision: "deny",
          permissionDecisionReason: reason,
        },
      });
    }
  }

  await touchFiles(agent, [rel]);
  await broadcastWorkspaceEvent(agent.workspaceId, { type: "agents_changed" });
  return new Response("", { status: 200 });
}
