#!/usr/bin/env python3
# PreToolUse on Edit|Write: who else is in this file? (the "room" is a JSON file here)
import sys, json, os, time
d = json.load(sys.stdin)
root = os.environ.get("CLAUDE_PROJECT_DIR") or d.get("cwd")
me = os.path.basename(root)
lab = os.path.dirname(root)
fp = d.get("tool_input", {}).get("file_path", "")
rel = os.path.relpath(fp, root) if fp else ""
pf = os.path.join(lab, "room", "editing.json")
af = os.path.join(lab, "room", "asked-%s.json" % me)
ed = json.load(open(pf)) if os.path.exists(pf) else {}
asked = json.load(open(af)) if os.path.exists(af) else []
now = time.time()
h = ed.get(rel)
if h and h["who"] != me and now - h["ts"] < 600 and rel not in asked:
    asked.append(rel); json.dump(asked, open(af, "w"))
    mins = max(1, int((now - h["ts"]) / 60))
    who = h["who"].capitalize()
    reason = (
        "STOPPED BY THE ROOM. %s is working in %s right now (started %d min ago). %s's task: \"%s\". "
        "Do not edit this file and do not try another way around. Tell the user this in one short sentence, "
        "then offer exactly these three choices and wait for their answer: "
        "1) Continue with the same edit anyway. "
        "2) A changed plan that fits with what %s is doing (write the concrete plan yourself). "
        "3) Message %s and wait (you would send it with the message_person tool)."
        % (who, rel, mins, who, h.get("intent", "unknown"), who, who))
    print(json.dumps({"hookSpecificOutput": {"hookEventName": "PreToolUse",
          "permissionDecision": "deny", "permissionDecisionReason": reason}}))
    sys.exit(0)
if rel and not (h and h["who"] != me):
    ed[rel] = {"who": me, "ts": now, "intent": (h or {}).get("intent", "")}
    json.dump(ed, open(pf, "w"))
